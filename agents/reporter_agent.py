"""ReporterAgent: Formats arbitration results into the exact hackathon JSON report schema and executive Markdown."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any, Dict, List

from protocol.models import ArbitrationResult, IncidentSummary, StructuredEvidence, UnifiedIncidentReport


class ReporterAgent:
    """Specialized agent responsible for deterministic report generation and markdown synthesis."""

    @staticmethod
    def generate_json_report(
        arbitration: ArbitrationResult,
        incident_id: str | None = None
    ) -> UnifiedIncidentReport:
        """Create schema-compliant UnifiedIncidentReport matching Page 5 of the NetCoop AI specification."""
        inc_id = incident_id or f"INC-{arbitration.execution_trace_id.replace('TRACE-', '')}"

        # Status: "diagnosed" or "insufficient_evidence"
        status = "insufficient_evidence" if arbitration.primary_root_cause == "INSUFFICIENT_EVIDENCE" else "diagnosed"

        # Alternative causes formatted as list of strings as specified in Page 5
        alt_causes = [
            f"Possible {alt['hypothesis'].replace('_', ' ').lower()}"
            for alt in arbitration.alternative_hypotheses
        ]

        # Structured supporting evidence items
        supporting = list(arbitration.structured_evidence)
        if not supporting and arbitration.supporting_evidence:
            for s in arbitration.supporting_evidence:
                supporting.append(StructuredEvidence(
                    metric="network_observation",
                    value="observed",
                    interpretation=s
                ))

        # Evidence sources list
        sources = list(arbitration.evidence_sources)
        if not sources:
            sources = ["telemetry_agent", "infrastructure_agent"]

        # Combine limitations and uncertainty factors
        combined_limitations = list(arbitration.limitations)
        for u in arbitration.uncertainty_factors:
            if u not in combined_limitations:
                combined_limitations.append(u)

        # Reported confidence: 0.0 when insufficient_evidence (can't be "36% sure of something")
        reported_confidence = 0.0 if status == "insufficient_evidence" else round(arbitration.confidence, 3)

        # Populate incidents[] when multiple co-occurring incidents are detected
        incidents_list = list(arbitration.co_occurring_incidents) if arbitration.co_occurring_incidents else []

        return UnifiedIncidentReport(
            incident_id=inc_id,
            status=status,
            suspected_root_cause=arbitration.primary_root_cause,
            confidence=reported_confidence,
            affected_devices=arbitration.affected_devices,
            supporting_evidence=supporting,
            alternative_causes=alt_causes,
            recommended_actions=arbitration.recommended_actions,
            evidence_sources=sources,
            limitations=combined_limitations,
            incidents=incidents_list
        )

    @staticmethod
    def generate_markdown_summary(
        report: UnifiedIncidentReport,
        evidence_completeness: float = 1.0
    ) -> str:
        """Synthesize a production-grade Executive Markdown Summary for network operators and judges."""
        timestamp_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

        conf_pct = round(report.confidence * 100, 1)
        if report.confidence >= 0.75:
            conf_badge = f"**HIGH** ({conf_pct}%)"
        elif report.confidence >= 0.45:
            conf_badge = f"**MEDIUM** ({conf_pct}%)"
        else:
            conf_badge = f"**LOW / INCONCLUSIVE** ({conf_pct}%)"

        md_lines = [
            f"# Network Incident Diagnostic Brief — {report.incident_id}",
            f"*Generated by NetCoop AI Multi-Agent Deterministic Engine at {timestamp_str}*",
            "",
            "## Executive Summary",
            f"- **Diagnosed Root Cause**: `{report.suspected_root_cause}`",
            f"- **Arbiter Confidence**: {conf_badge}",
            f"- **Telemetry Completeness**: {round(evidence_completeness * 100, 1)}%",
            f"- **Total Affected Devices**: {len(report.affected_devices)}",
            "",
            "## Impact Assessment & Blast Radius",
            f"The incident impacts **{len(report.affected_devices)}** network infrastructure elements:",
        ]

        if report.affected_devices:
            for dev in report.affected_devices:
                md_lines.append(f"  - `{dev}`")
        else:
            md_lines.append("  - *No anomalous devices detected; network operating normally.*")

        md_lines.extend([
            "",
            "## Evidentiary Audit Trail",
            "Deterministic findings established across specialized agents:",
        ])

        if report.supporting_evidence:
            for item in report.supporting_evidence:
                if isinstance(item, StructuredEvidence):
                    md_lines.append(f"- **{item.metric}** (`{item.value}`): {item.interpretation}")
                else:
                    md_lines.append(f"- {item}")
        else:
            md_lines.append("- *No supporting evidence recorded.*")

        if report.alternative_causes:
            md_lines.extend([
                "",
                "## Alternative Diagnostic Hypotheses Evaluated",
            ])
            for alt in report.alternative_causes:
                md_lines.append(f"- `{alt}`")

        md_lines.extend([
            "",
            "## Actionable Remediation Playbook",
        ])
        for idx, action in enumerate(report.recommended_actions, 1):
            md_lines.append(f"{idx}. {action}")

        if report.limitations:
            md_lines.extend([
                "",
                "## Known Limitations & Uncertainty Factors",
            ])
            for lim in report.limitations:
                md_lines.append(f"- {lim}")

        md_lines.extend([
            "",
            "---",
            "*NetCoop AI Hackathon — Deterministic Multi-Agent Network Intelligence Architecture*"
        ])

        return "\n".join(md_lines)
